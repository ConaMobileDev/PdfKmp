/** A live demonstration of the `pdfkmp-markdown` companion on the web backend. */
private fun markdownDemo(): PdfDocument = pdf {
    metadata { title = "Markdown on the Web" }
    page {
        markdown(
            """
            # Markdown → PDF

            This page was written in **Markdown** and rendered by the
            `pdfkmp-markdown` module — *inside your browser*, on Kotlin/Wasm.

            ## What the parser understands

            - Headings, **bold**, *italic*, and `inline code`
            - Ordered and unordered lists
            - Blockquotes and horizontal rules
            - Fenced code blocks
            - Links: [PdfKmp on GitHub](https://github.com/ConaMobileDev/PdfKmp)

            ## A pipe table

            | Module | Purpose |
            | --- | --- |
            | `pdfkmp` | Core DSL + layout + writers |
            | `pdfkmp-markdown` | This very renderer |

            > No JavaScript PDF library was harmed in the making of this
            > document — the bytes come from PdfKmp's pure-Kotlin writer.
            """.trimIndent(),
        )
    }
}

/** Appends a styled sample button to the `#samples` grid in index.html. */
@JsFun(
    """(label, desc, handler) => {
        const btn = document.createElement('button');
        btn.className = 'sample';
        const name = document.createElement('span');
        name.className = 'name';
        name.textContent = label;
        const sub = document.createElement('span');
        sub.className = 'desc';
        sub.textContent = desc;
        btn.appendChild(name);
        btn.appendChild(sub);
        btn.addEventListener('click', handler);
        document.getElementById('samples').appendChild(btn);
    }""",
)
private external fun addSampleButton(label: String, desc: String, handler: () -> Unit)

/** Replaces the `#status` line under the grid. */
@JsFun("(text) => { document.getElementById('status').textContent = text; }")
private external fun setStatus(text: String)

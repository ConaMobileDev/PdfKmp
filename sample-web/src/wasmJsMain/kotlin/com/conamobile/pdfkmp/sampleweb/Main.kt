package com.conamobile.pdfkmp.sampleweb

import com.conamobile.pdfkmp.PdfDocument
import com.conamobile.pdfkmp.markdown.markdown
import com.conamobile.pdfkmp.openInNewTab
import com.conamobile.pdfkmp.pdf
import com.conamobile.pdfkmp.samples.Samples
import com.conamobile.pdfkmp.storage.StorageLocation
import com.conamobile.pdfkmp.storage.save

/**
 * Entry point of the Web (Kotlin/Wasm) sample. Builds a button per sample
 * document; each click generates the PDF in the browser and hands it to the
 * browser's own viewer via [openInNewTab] — PdfKmp ships no web viewer on
 * purpose. When a pop-up blocker eats the tab, the document falls back to a
 * regular download.
 */
fun main() {
    webSamples().forEach { sample ->
        addSampleButton(sample.name, sample.description) {
            val document = sample.make()
            if (document.openInNewTab()) {
                setStatus("Opened “${sample.name}” in a new tab.")
            } else {
                document.save(StorageLocation.Downloads, "${sample.fileName}.pdf")
                setStatus("Pop-up blocked — downloaded ${sample.fileName}.pdf instead.")
            }
        }
    }
    setStatus("Pick a document — it is generated right here in Wasm.")
}

private class WebSample(
    val name: String,
    val fileName: String,
    val description: String,
    val make: () -> PdfDocument,
)

